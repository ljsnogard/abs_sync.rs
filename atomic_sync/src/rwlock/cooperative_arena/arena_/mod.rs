//! 协作式读写锁等待节点专用的对象池。
//!
//! # 为什么需要它
//!
//! `RwCore` 的等待队列目前是 `VecDeque<Arc<WaitNode>>`：每个等待节点都要一次
//! `Arc` 分配，队列增长时还要搬运 `Arc` 指针数组。等待队列天然是 FIFO，
//! 而且"越早入队、越早被回收"，因此更适合把节点本体放进分块池，并把前驱/
//! 后继指针直接嵌进节点，做成侵入式链表。
//!
//! # 结构
//!
//! - [`Arena<T, A>`] 只保存头/尾两个 chunk 指针（外加一份分配器 `A`）；
//! - `Chunk<T, A>` 之间用 `prev_` / `next_` 双向链接；
//! - 每个 chunk 固定 1024 个槽位，槽位里的 `self_idx_: u16` 记录自己的下标，
//!   `next_free_: u16` 把空闲槽位串成 chunk 内的空闲链；
//! - 分配只动 `tail_` chunk 的 `free_head_` 与槽位的 `next_free_`，回收时把
//!   槽位压回所属 chunk 的空闲链头，因此支持少量不按顺序的释放；
//! - 槽位的 `self_idx_` 加固定布局偏移可以 O(1) 反推 chunk 基址，槽位里不必
//!   再存 chunk 指针，也不需要沿 chunk 链扫描；
//! - 非 `tail_` 的 chunk 一旦清空就立即归还分配器，`tail_` 即使空了也保留，
//!   作为下一次分配的当前块。
//!
//! 只有"申请新 chunk"和"摘除空 chunk"需要动 chunk 链指针；绝大多数分配/回收
//! 都只在一个 chunk 内做 `u16` 索引操作。
//!
//! # 地址稳定性
//!
//! chunk 由分配器整块申请，之后不会搬移；一个槽位只要还存活，它的地址就不会
//! 改变。因此 `alloc` 返回的 `NonNull<T>` 可以长期保存，直接用作等待队列节点
//! 之间的前后驱链接。
//!
//! # 安全边界
//!
//! 池不做内部同步：修改需要 `&mut Arena`，共享访问必须由外部锁（等待队列的
//! 自旋锁）串行化。`alloc` 是安全函数；`get` / `get_mut` / `free` 依赖调用方
//! 保证句柄来自本池、仍然存活且没有别名引用，因此是 `unsafe`。
//!
//! # 模块组织
//!
//! - `chunk_`：定长 chunk、槽位布局、空闲链初始化与 chunk 反推；
//! - `pool_`：[`Arena`] 本体（分配、回收、chunk 链维护、析构）；
//! - `tests_`：单元测试。

